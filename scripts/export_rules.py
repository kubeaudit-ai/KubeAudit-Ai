"""Write web/src/rules.js from app/rules.py so the web app shows identical rule text."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.rules import RULES, SEVERITY_ORDER, DANGEROUS_CAPS, SECRET_NAME, LONG_RUNNING, POD_SPEC_PATHS, IGNORE_ANNOTATION

data = {
    "RULES": {r.id: {"id": r.id, "name": r.name, "severity": r.severity, "title": r.title,
                     "remediation": r.remediation, "fix": r.fix, "docs": r.docs} for r in RULES.values()},
    "SEVERITY_ORDER": SEVERITY_ORDER,
    "DANGEROUS_CAPS": sorted(DANGEROUS_CAPS),
    "SECRET_NAME": SECRET_NAME.pattern,
    "LONG_RUNNING": sorted(LONG_RUNNING),
    "POD_SPEC_PATHS": {k: list(v) for k, v in POD_SPEC_PATHS.items()},
    "IGNORE_ANNOTATION": IGNORE_ANNOTATION,
}
out = Path(__file__).resolve().parent.parent / "web" / "src" / "rules.js"
out.write_text("// Generated by scripts/export_rules.py from app/rules.py. Do not edit by hand.\n"
               "export const DATA = " + json.dumps(data, indent=2) + ";\n")
print(f"wrote {out}")
